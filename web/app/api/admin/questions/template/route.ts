import ExcelJS from 'exceljs';
import type { NextRequest } from 'next/server';
import '@/lib/excel-patch';
import { TEMPLATE_HEADERS } from '@/lib/question-import';
import { getRequestAccessToken } from '@/lib/server-access-token';

export async function GET(request: NextRequest) {
  if (!await getRequestAccessToken(request)) return Response.json({ message: 'Authentication is required' }, { status: 401 });
  const workbook = new ExcelJS.Workbook();
  const sheet = workbook.addWorksheet('Questions');
  sheet.addRow([...TEMPLATE_HEADERS]);
  sheet.addRow([
    'PHYSICS', 'Units and Measurements', 'SINGLE_CORRECT', 'MEDIUM',
    'தமிழ் கேள்வி', 'English question text', '',
    'விருப்பம் 1', 'Option 1', '',
    'விருப்பம் 2', 'Option 2', '',
    'விருப்பம் 3', 'Option 3', '',
    'விருப்பம் 4', 'Option 4', '',
    '2', '', 'தமிழ் தீர்வு', 'English solution', '', 4, 1, 'NEET practice'
  ]);
  sheet.getRow(1).font = { bold: true, color: { argb: 'FFFFFFFF' } };
  sheet.getRow(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF18134F' } };
  sheet.views = [{ state: 'frozen', ySplit: 1 }];
  sheet.autoFilter = { from: 'A1', to: 'AA1' };
  sheet.columns.forEach((column) => { column.width = 22; });
  sheet.getRow(2).height = 90;

  TEMPLATE_HEADERS.forEach((header, index) => {
    if (header.endsWith('_image')) {
      sheet.getColumn(index + 1).width = 28;
      sheet.getCell(2, index + 1).note = 'Insert a JPG/PNG picture here and resize it completely inside this cell. Import uploads it to Supabase automatically. A public HTTPS URL is also supported.';
      sheet.getCell(2, index + 1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFFFF7D6' } };
    }
  });

  const instructions = workbook.addWorksheet('Instructions');
  [
    ['Field', 'Allowed value / rule'],
    ['external_id & course_code', 'Auto-generated by system during import. You do NOT need to provide external_id or course_code in Excel.'],
    ['subject_code', 'PHYSICS, CHEMISTRY or BIOLOGY'],
    ['question_type', 'SINGLE_CORRECT, MULTIPLE_CORRECT or NUMERICAL'],
    ['difficulty', 'EASY, MEDIUM or HARD'],
    ['correct_options', '1 for single answer; 1,3 for multiple answers; blank for numerical (or A/B/C/D)'],
    ['image columns', 'Insert > Pictures, place one JPG/PNG completely inside the matching *_image cell. Import uploads it to Supabase automatically. Existing public HTTPS URLs also work.'],
    ['embedded image limits', 'Maximum 100 pictures per workbook, 5 MB per picture and 25 MB workbook.'],
    ['marks', 'NEET default is +4 correct and -1 wrong'],
    ['source', 'Optional. Defaults to "NEET practice" if blank.'],
    ['chapter policy', 'If chapter_title does not exist, bulk import creates it under the matching course_code and subject_code, then maps the question to it.'],
    ['batch limit', 'Maximum 500 non-empty question rows per workbook.'],
    ['Important', 'Do not rename header columns. External IDs and course codes are auto-generated automatically.'],
  ].forEach((row) => instructions.addRow(row));

  instructions.getRow(1).font = { bold: true };
  instructions.columns = [{ width: 26 }, { width: 100 }];

  const bytes = await workbook.xlsx.writeBuffer();
  return new Response(Buffer.from(bytes), {
    headers: {
      'Content-Type': 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
      'Content-Disposition': 'attachment; filename="isharp-neet-question-template.xlsx"',
      'Cache-Control': 'no-store'
    }
  });
}
